"""Create a realistic multi-system "company" for the live connector demo.

    python scripts/generate_demo_sources.py        # writes data/demo/* and sources.yaml
    python scripts/demo_servers.py                 # starts the demo FTP + REST servers
    uvicorn backend.main:app                       # KAIROS picks the sources up from sources.yaml

What gets created (all timestamps end "now", with the same injected incidents as the
synthetic demo so the causal story is identical):

  ERP database     data/demo/erp.sqlite            RAW order rows -> SQL connector aggregates
                                                    inside SQLite (push-down), only KPIs travel
  Marketing files  data/demo/exports/*.csv          wide hourly KPI exports -> File connector
  Logistics (S)FTP data/demo/ftp/kpis/*.csv.gz      one compressed file per day -> FTP connector,
                                                    only new files are downloaded
  Support REST API served by demo_servers.py        paged JSON -> REST connector
  ERP KPIs         pushed by the edge agent         (see README)
"""
from __future__ import annotations

import sqlite3
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.demo.synthetic import generate  # noqa: E402

DEMO = ROOT / "data" / "demo"

SOURCES_YAML = """# Generated by scripts/generate_demo_sources.py — the live connector demo.
# Every connector type KAIROS supports is configured here; secrets come from env vars.
# See sources.example.yaml for all options.
sources:
  - name: erp_sqlite
    type: sql
    description: ERP order table (raw rows) — aggregated inside the database (push-down)
    url: sqlite:///{erp}
    query: |
      SELECT strftime('%Y-%m-%d %H:00:00', created_at) AS timestamp,
             SUM(amount)  AS daily_revenue,
             COUNT(*)     AS order_count,
             AVG(amount)  AS avg_order_value,
             SUM(CASE WHEN status = 'refunded' THEN 1 ELSE 0 END) AS refund_count
      FROM orders
      WHERE created_at >= :since
      GROUP BY 1
    ts_col: timestamp
    format: wide

  - name: marketing_exports
    type: file
    description: Marketing team's hourly CSV exports (one file per week)
    path: {exports}/marketing_*.csv
    ts_col: hour
    format: wide

  - name: logistics_ftp
    type: sftp
    protocol: ftp              # use sftp or ftps in production
    description: Logistics KPIs dropped daily on an FTP server as compressed CSV
    host: 127.0.0.1
    port: 2121
    username: kairos
    password_env: DEMO_FTP_PASS
    folder: /kpis
    pattern: "logistics_*.csv.gz"
    format: long
    metric_col: kpi
    value_col: value
    ts_col: ts

  - name: support_api
    type: rest
    description: Customer-support platform REST API (paged JSON)
    url: http://127.0.0.1:8090/api/v1/kpis
    headers: {{Authorization: "Bearer ${{DEMO_API_TOKEN}}"}}
    records_path: data
    since_param: since
    pagination: {{type: page, param: page, max_pages: 200}}
    ts_col: hour
    format: wide
"""


def main() -> None:
    DEMO.mkdir(parents=True, exist_ok=True)
    df = generate()                                   # long: source, metric_name, timestamp, value
    wide = df.pivot_table(index="timestamp", columns="metric_name", values="value").sort_index()
    rng = np.random.default_rng(11)

    # 1. ERP: explode hourly KPIs into raw order rows so SUM/COUNT reproduce them
    erp = DEMO / "erp.sqlite"
    erp.unlink(missing_ok=True)
    rows = []
    for ts, r in wide.iterrows():
        n = max(1, int(round(r["order_count"])))
        aov = r["daily_revenue"] / n
        amounts = np.maximum(1, rng.normal(aov, aov * 0.25, n))
        amounts *= r["daily_revenue"] / amounts.sum()
        refunds = min(n, max(0, int(round(r["refund_count"]))))
        status = np.array(["paid"] * n, dtype=object)
        status[rng.choice(n, refunds, replace=False)] = "refunded"
        secs = np.sort(rng.integers(0, 3600, n))
        for k in range(n):
            rows.append(((ts + pd.Timedelta(seconds=int(secs[k]))).strftime("%Y-%m-%d %H:%M:%S"),
                         round(float(amounts[k]), 2), status[k]))
    orders = pd.DataFrame(rows, columns=["created_at", "amount", "status"])
    orders.insert(0, "order_id", np.arange(1, len(orders) + 1))
    with sqlite3.connect(erp) as con:
        orders.to_sql("orders", con, index=False)
        con.execute("CREATE INDEX idx_orders_created ON orders(created_at)")
    print(f"ERP           {erp}  ({len(orders):,} raw order rows)")

    # 2. Marketing CSV exports, one wide file per week
    exports = DEMO / "exports"
    exports.mkdir(exist_ok=True)
    for f in exports.glob("marketing_*.csv"):
        f.unlink()
    mk = wide[["ad_spend_usd", "click_through_rate", "conversion_rate", "cart_abandonment_rate"]].round(4)
    mk.index = mk.index.strftime("%Y-%m-%d %H:%M:%S")
    mk.index.name = "hour"
    weeks = pd.to_datetime(mk.index).to_period("W")
    for wk, part in mk.groupby(weeks):
        part.to_csv(exports / f"marketing_{wk.start_time:%Y_%m_%d}.csv")
    print(f"Marketing     {exports}  ({len(list(exports.glob('*.csv')))} weekly CSV files)")

    # 3. Logistics FTP drop: one gzip file per day, long format
    ftp = DEMO / "ftp" / "kpis"
    ftp.mkdir(parents=True, exist_ok=True)
    for f in ftp.glob("*.csv.gz"):
        f.unlink()
    lg = df[df["source"] == "rest_api_logistics"].rename(columns={"metric_name": "kpi", "timestamp": "ts"})
    lg = lg[["ts", "kpi", "value"]].copy()
    lg["value"] = lg["value"].round(4)
    for day, part in lg.groupby(lg["ts"].dt.strftime("%Y-%m-%d")):
        part.assign(ts=part["ts"].dt.strftime("%Y-%m-%dT%H:%M:%SZ")).to_csv(
            ftp / f"logistics_{day}.csv.gz", index=False, compression="gzip")
    print(f"Logistics FTP {ftp}  ({len(list(ftp.glob('*.gz')))} daily .csv.gz files)")

    # 4. Support API data (served by demo_servers.py)
    cs = wide[["support_tickets_open", "avg_response_time_hrs", "nps_score", "customer_churn_rate"]].round(4)
    cs = cs.reset_index().rename(columns={"timestamp": "hour"})
    cs["hour"] = cs["hour"].dt.strftime("%Y-%m-%dT%H:%M:%SZ")
    cs.to_json(DEMO / "support_api.json", orient="records")
    print(f"Support API   {DEMO / 'support_api.json'}  ({len(cs)} hourly records)")

    # 5. a raw export for the edge-agent / fast-transfer demo
    tx = orders.sample(frac=1.0, random_state=1).sort_values("created_at")
    tx.to_csv(DEMO / "erp_orders_raw.csv.gz", index=False, compression="gzip")
    print(f"Raw export    {DEMO / 'erp_orders_raw.csv.gz'}  (for the edge agent / Fast Transfer demo)")

    yaml_text = SOURCES_YAML.format(erp=erp.as_posix(), exports=exports.as_posix())
    (ROOT / "sources.yaml").write_text(yaml_text, encoding="utf-8")
    print(f"\nwrote {ROOT / 'sources.yaml'}")
    print("next: python scripts/demo_servers.py   (FTP on :2121, REST on :8090), then start KAIROS")


if __name__ == "__main__":
    main()
